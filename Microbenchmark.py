#!/usr/bin/env python3
"""Benchmarks for the signature-free ML-KEM anamorphic AKE paper.

The script produces the measurements required by Section 5 of the paper:

1. Protocol performance: ML-KEM, HKDF/HMAC, AEAD, complete AKE, ordinary
   records, anamorphic records, throughput, trials, and serialized sizes.
2. Anamorphic detectability: entropy, frequency, chi-square, KS/TV distance,
   classifier accuracy, balanced accuracy, and ROC-AUC.

No paper result is hard-coded.  Every CSV value is generated by the current
machine and the command-line configuration recorded in metadata.json.
"""

